const revenueMultiple = 0.6;
const profitMultiple = 3;

function buildValuation(annualRevenue, annualProfit) {
  const revenueBasedValue = Math.round(annualRevenue * revenueMultiple);
  const profitBasedValue = Math.round(annualProfit * profitMultiple);
  const fairValue = Math.round((revenueBasedValue + profitBasedValue) / 2);
  return {
    revenueMultiple,
    profitMultiple,
    revenueBasedValue,
    profitBasedValue,
    fairValue,
  };
}

